"""Intersections N_s cap N_s' of two members of a family of subfactors.

Run with ``python intersection_demo.py``.

Every connection in a family on fixed graphs gives a subfactor N_s of one and
the same M: in the H picture the tower A_{n,1} and its Jones projections do not
depend on the connection, which only moves A_{n,0}^(s) = W_s^* (K algebra) W_s.
So P cap Q = N_s cap N_s' is a subalgebra of M, and everything about it reduces
to finite dimensions (see pathalg/intersection.py):

  * The angle operator T = e_P e_Q e_P restricted to L^2(A_{n,1}) has
    spec(T_n) inside spec(T), increasing with n, and spec(T) is the closure of
    their union: every eigenvalue printed below is exactly an eigenvalue of T.
  * E_{P cap Q}(A_{n,1}) = C_n := A_{n,0}^(s) cap A_{n,0}^(s'), and P cap Q is
    generated by the C_n.  Its centre is the space of bounded harmonic
    functions on the Bratteli diagram of the C_n with the Markov trace.
  * Finite index of P cap Q forces a finite spectrum, since e_P, e_Q then lie
    in the finite dimensional (P cap Q)' cap M_1.

For each level the table gives

  dim C_n           the eigenvalue 1 multiplicity
  angles            the number of distinct eigenvalues of T_n in (0, 1): if it
                    keeps growing, spec(T) is infinite and the index is too
  top < 1           the largest eigenvalue below 1: nondecreasing in n; 1 is
                    isolated in spec(T) exactly when it stays away from 1
  ||L||^2           ||Lambda(C_n < A_{n,1})||^2.  It equals [M : P cap Q] at
                    every level in the finite index cases checked in part A;
                    growth points to infinite index
  centre, dobrushin the centre of C_n, and the Dobrushin coefficient of the
                    chain from C_1 to C_n: tending to 0 is the factor case;
                    stuck at 1 means the Bratteli diagram has split

Part A checks all of this against Bakshi-Guin-Guruprasad, "Intersection of
conjugate Hadamard subfactors arising from Fourier matrices",
arXiv:2510.14499, Theorem B: [R : R_U cap R_V] = N^2 / |H| with
|H| = dim(Ad_U(Delta) cap Ad_V(Delta)), a factor.  Part B is the S(1,1,2,2)
family of ah_demo.py.
"""

from __future__ import annotations

import time

import sympy as sp

import ah_demo
from pathalg import InsufficientMemory
from pathalg.examples import fourier_matrix, hadamard
from pathalg.intersection import LevelPair, analyse

# ------------------------------------------------------------------- 0. knobs

# Double precision only: "numpy" (CPU) or "cupy" (GPU, complex128).  Counting
# distinct eigenvalues needs the digits; complex64 cannot separate them.
BACKEND = "numpy"

# Levels n = 1 .. MAX_N.  Dense throughout: n = 4 is seconds, n = 5 about a
# minute per pair on the CPU (dim A_{5,0} = 4160), n = 6 is out of reach densely.
MAX_N = 4

# Part A: N x N Fourier matrix, and the diagonal unitaries D.  The pair is
# U = F_N and V = D U in the paper's notation, which is F_N D here because the
# library's Hadamard matrix is the paper's U^*.  Row phases would be a gauge
# change and give the same subfactor.
HADAMARD_N = 4
I = sp.I
HADAMARD_D = {
    "diag(1, 1, 1, -1)": [1, 1, 1, -1],
    "diag(1, 1, -1, -1)": [1, 1, -1, -1],
    "diag(1, 1, i, i)": [1, 1, I, I],
    "diag(1, e^i, e^2i, e^3i)": [1, sp.exp(I), sp.exp(2 * I), sp.exp(3 * I)],
    "diag(1, i, -1, -i)  (a row shift)": [1, I, -1, -I],
}

# Part B: s fixed, s' swept.  The grid includes the symmetric partners of s.
S = sp.pi / 3
S_PRIMES = [
    sp.pi / 3,                    # s' = s: the sanity check, C_n = A_{n,0}
    sp.pi / 2,
    sp.Rational(7, 5),
    2 * sp.pi / 3,                # pi - s
    sp.pi,
    4 * sp.pi / 3,                # pi + s
    5 * sp.pi / 3,                # 2 pi - s
    sp.Rational(1, 10),
]


# -------------------------------------------------------------- the report


def table(result):
    header = ("n", "dim A_n0", "dim C_n", "angles", "top < 1", "||L||^2",
              "centre", "dobrushin")
    print("    {:>2}  {:>8}  {:>7}  {:>6}  {:>9}  {:>9}  {:>6}  {:>9}".format(*header))
    for r in result.records:
        sp_ = r.spectrum
        top = "-" if sp_.top is None else f"{sp_.top:.6f}"
        dob = "-" if r.dobrushin is None else f"{r.dobrushin:.4f}"
        print(f"    {r.p:>2}  {sp_.dim:>8}  {sp_.dim_intersection:>7}  "
              f"{len(sp_.distinct):>6}  {top:>9}  {r.index_estimate:>9.4f}  "
              f"{r.algebra.centre_dim:>6}  {dob:>9}")
    persistent = [c for c in result.components if len(c.levels) == len(result.records)]
    if len(persistent) > 1:
        print(f"    the Bratteli diagram splits into {len(persistent)} components at "
              "every level: central projections of every C_n")
        for c in persistent:
            where = (f"= the projection onto paths starting at {', '.join(c.starts)}"
                     if c.starts else "(not diagonal in the path basis)")
            print(f"      tau = {c.trace:.6f}  {where}")


def run_pair(label, square_s, square_t):
    print(f"\n  {label}")
    start = time.time()
    try:
        pair = LevelPair(square_s, square_t, MAX_N, backend=BACKEND)
        result = analyse(pair)
    except InsufficientMemory as exc:
        print(f"    skipped: {exc}")
        return None
    table(result)
    print(f"    ({time.time() - start:.1f}s)")
    return result


def main():
    print("=" * 76)
    print(f"A. Hadamard validation, F_{HADAMARD_N}: Theorem B of arXiv:2510.14499")
    print("=" * 76)
    print("  Expected: ||L||^2 = N^2 / |H| at every level, |H| = dim C_1; a finite")
    print("  spectrum (the angle count does not grow); a factor (dobrushin -> 0).")
    F = fourier_matrix(HADAMARD_N)
    square_F = hadamard(F, backend=BACKEND)
    for name, d in HADAMARD_D.items():
        V = F * sp.diag(*d)
        result = run_pair(f"V = D U with D = {name}", square_F, hadamard(V, backend=BACKEND))
        if result is not None:
            h = result.records[0].spectrum.dim_intersection
            print(f"    |H| = {h},  N^2 / |H| = {HADAMARD_N ** 2 / h:g}")

    print("\n" + "=" * 76)
    print(f"B. S(1,1,2,2): s = {S} against a range of s'")
    print("=" * 76)
    print(f"  delta^2 = [M : N_s] = {float(sp.N(ah_demo.DELTA ** 2)):.6f}")
    square_s = ah_demo.ah_square(S, backend=BACKEND)
    for s2 in S_PRIMES:
        run_pair(f"s' = {s2}", square_s, ah_demo.ah_square(s2, backend=BACKEND))

    print("\ndone.")


if __name__ == "__main__":
    main()
