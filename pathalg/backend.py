"""Scalar / matrix backends.

Two interchangeable backends are provided:

``SympyBackend``  exact symbolic arithmetic (the default),
``ArrayBackend``  floating point on a numpy-like namespace -- numpy or cupy,
                  at ``complex128`` or ``complex64``.

Everything downstream (path spaces, block operators, the tower) is written
against the small duck-typed interface below, so switching backend is a
one-word change: ``Level(square, n, backend="cupy64")`` runs the whole tower
on the GPU in single precision.
"""

from __future__ import annotations

import cmath

import sympy as sp

__all__ = [
    "SympyBackend",
    "ArrayBackend",
    "NumpyBackend",
    "InsufficientMemory",
    "get_backend",
    "gpu_available",
    "host_available_memory",
]


class SympyBackend:
    """Exact arithmetic on :class:`sympy.Matrix` blocks."""

    name = "sympy"
    exact = True

    def __init__(self, level: int = 1, tol: float = 1e-9):
        """``level`` controls how hard :meth:`simp` works on intermediate results.

        0 = leave entries alone, 1 = ``expand`` (the default: enough to keep
        expressions from growing, cheap enough to run on every entry),
        2 = ``radsimp`` of a full ``sympy.simplify`` (much slower, and on
        cyclotomic entries usually *less* compact -- see :meth:`simp`).
        Zero testing is unaffected: it always screens numerically first and
        then falls back to full simplification, so a lower level costs
        readability, never correctness.
        """
        self.level = level
        self.tol = tol
        self._zero_cache = {}

    # ------------------------------------------------------------------ scalars
    def num(self, x):
        return sp.sympify(x)

    def conj(self, x):
        return sp.conjugate(sp.sympify(x))

    def sqrt(self, x):
        return sp.sqrt(sp.sympify(x))

    def simp(self, x):
        """Normalise an entry.

        Plain ``expand`` is the sweet spot, and the choice matters a lot.
        Connection entries are naturally written with ``exp(i pi q)`` factors,
        which sympy already collapses on multiplication; ``expand`` keeps them
        in that form.  ``radsimp``, ``powsimp`` and ``expand_complex`` all
        rewrite them as nested radicals such as ``sqrt(-4 - 2 sqrt(2))``, which
        never collapse again and make later arithmetic orders of magnitude
        slower.  Zero testing does its own exact fallback, so the light touch
        here costs nothing in correctness.
        """
        x = sp.sympify(x)
        if x.is_Atom:
            return x
        try:
            if self.level <= 0:
                return x
            if self.level == 1:
                return sp.expand(x)
            return sp.radsimp(sp.simplify(x))
        except Exception:
            try:
                return sp.expand(x)
            except Exception:
                return x

    def to_complex(self, x):
        return complex(sp.N(sp.sympify(x), 30))

    def _exactly_zero(self, exprs):
        """Decide exact vanishing of a batch of expressions, in one number field.

        Everything here lives in the field generated by the connection entries
        and the Perron-Frobenius weights, so the reliable and fast way to settle
        ``x == 0`` is to map into that field, where zero has a unique
        representative.  Doing it for a whole batch at once amortises the cost
        of finding a primitive element, which is why matrix-level zero tests go
        through here rather than looping over :meth:`is_zero`.
        ``simplify`` is only the last resort, for entries that are not algebraic
        numbers at all.
        """
        exprs = list(exprs)
        if not exprs:
            return True
        try:
            from sympy.polys.matrices import DomainMatrix

            dm = DomainMatrix.from_Matrix(sp.Matrix([exprs]), extension=True)
            zero = dm.domain.zero
            if all(e == zero for row in dm.to_list() for e in row):
                return True
            # A "not zero" verdict is only meaningful when sympy actually found
            # a number field.  It falls back to the generic expression domain
            # EX for entries it cannot place -- nested radicals mixed with roots
            # of unity, for instance -- and there a true zero written in two
            # different forms compares unequal.  Trusting that would report
            # spurious failures, so drop through to a symbolic decision.
            if self._reliable_domain(dm.domain):
                return False
        except Exception:
            pass
        try:
            return all(sp.simplify(sp.expand_complex(e)) == 0 for e in exprs)
        except Exception:
            return False

    @staticmethod
    def _reliable_domain(domain):
        """Domains in which equality of representatives really is equality."""
        return any(
            getattr(domain, flag, False)
            for flag in ("is_AlgebraicField", "is_QQ", "is_ZZ", "is_QQ_I", "is_ZZ_I")
        )

    def is_zero(self, x):
        """Cheap symbolic test, then a numeric screen, then an exact decision."""
        x = sp.sympify(x)
        if x == 0:
            return True
        try:
            x = sp.expand(x)
            if x == 0:
                return True
        except Exception:
            pass
        try:
            if abs(self.to_complex(x)) > self.tol:
                return False
        except (TypeError, ValueError):
            pass
        # Numerically indistinguishable from zero: settle it exactly.  The same
        # near-zero expressions recur constantly, so the verdict is cached.
        cached = self._zero_cache.get(x)
        if cached is None:
            cached = self._exactly_zero([x])
            if len(self._zero_cache) > 20000:
                self._zero_cache.clear()
            self._zero_cache[x] = cached
        return cached

    # ----------------------------------------------------------------- matrices
    def zeros(self, r, c):
        return sp.zeros(r, c)

    def eye(self, n):
        return sp.eye(n)

    def shape(self, A):
        return (A.rows, A.cols)

    def dagger(self, A):
        if A.rows == 0 or A.cols == 0:
            return sp.zeros(A.cols, A.rows)
        return A.conjugate().T

    def mul(self, A, B):
        if A.cols == 0:
            return sp.zeros(A.rows, B.cols)
        return A * B

    def add(self, A, B):
        return A + B

    def sub(self, A, B):
        return A - B

    def smul(self, s, A):
        return sp.sympify(s) * A

    def trace(self, A):
        return sp.Add(*[A[i, i] for i in range(A.rows)]) if A.rows else sp.Integer(0)

    def mat_is_zero(self, A):
        """Batched zero test: cheap screens first, then one field conversion."""
        if A.rows == 0 or A.cols == 0:
            return True
        try:
            entries = [sp.expand(e) for e in A]
        except Exception:
            entries = list(A)
        undecided = []
        for e in entries:
            if e == 0:
                continue
            try:
                if abs(self.to_complex(e)) > self.tol:
                    return False
            except (TypeError, ValueError):
                pass
            undecided.append(e)
        return self._exactly_zero(undecided)

    def simp_mat(self, A):
        return A.applyfunc(self.simp)

    def _echelon(self, A):
        """Reduced row echelon basis of the row space, as ``(pivot cols, rows)``.

        Rolled by hand rather than calling ``Matrix.rref``: the systems here are
        tall and thin (many more rows than columns) with messy algebraic
        entries, and sympy's rref works across the whole matrix, which swells
        the intermediate expressions badly -- a 96 x 16 system took over three
        minutes that way and under a second like this.  Rows are folded in one
        at a time against an echelon basis that never exceeds ``A.cols`` rows,
        and the pivot within a new row is chosen by largest numeric magnitude,
        which keeps the entries that get divided through well away from zero.
        """
        piv, rows = [], []
        for r in range(A.rows):
            v = [self.simp(A[r, j]) for j in range(A.cols)]
            for p, row in zip(piv, rows):
                if self.is_zero(v[p]):
                    continue
                f = v[p]
                v = [self.simp(a - f * b) for a, b in zip(v, row)]
            best, best_mag = None, 0.0
            for j, x in enumerate(v):
                if self.is_zero(x):
                    continue
                try:
                    mag = abs(self.to_complex(x))
                except (TypeError, ValueError):
                    mag = 1.0
                if best is None or mag > best_mag:
                    best, best_mag = j, mag
            if best is None:
                continue
            lead = v[best]
            v = [self.simp(a / lead) for a in v]
            # keep the basis fully reduced so back substitution is immediate
            for i, row in enumerate(rows):
                if not self.is_zero(row[best]):
                    f = row[best]
                    rows[i] = [self.simp(a - f * b) for a, b in zip(row, v)]
            piv.append(best)
            rows.append(v)
            if len(piv) == A.cols:
                break
        return piv, rows

    def nullspace(self, A):
        """A list of flat coordinate lists spanning ``ker(A)``.

        The fast path puts the whole matrix into the number field its entries
        generate and eliminates there, where every element has a canonical
        representative and nothing can swell.  This matters enormously: a
        96 x 16 system from a Dynkin connection takes 0.3s this way and over
        three minutes with elimination on raw sympy expressions, because
        dividing by an algebraic pivot produces denominators that no cheap
        normalisation clears (operation counts observed to go 43 -> 618 ->
        126000 over three pivots).  Entries that are not algebraic numbers
        (free symbols, say) fall back to :meth:`_echelon`.
        """
        if A.cols == 0:
            return []
        if A.rows == 0:
            return [list(sp.eye(A.cols)[:, j]) for j in range(A.cols)]
        try:
            from sympy.polys.matrices import DomainMatrix

            ns = DomainMatrix.from_Matrix(A, extension=True).nullspace().to_Matrix()
            return [list(ns.row(i)) for i in range(ns.rows)]
        except Exception:
            pass
        piv, rows = self._echelon(A)
        pivset = set(piv)
        out = []
        for free in range(A.cols):
            if free in pivset:
                continue
            vec = [sp.Integer(0)] * A.cols
            vec[free] = sp.Integer(1)
            for p, row in zip(piv, rows):
                vec[p] = self.simp(-row[free])
            out.append(vec)
        return out

    def rank(self, A):
        if A.rows == 0 or A.cols == 0:
            return 0
        return A.cols - len(self.nullspace(A))


class ArrayBackend:
    """Floating point arithmetic on the arrays of some numpy-like namespace.

    ``xp`` is the array module -- ``numpy`` or ``cupy`` -- and ``dtype`` the
    complex type the blocks are stored in.  Every hot path in :mod:`tower` is
    written as whole-array operations on stacks of shape ``(k, d, d)``, so the
    only thing that distinguishes CPU from GPU is which module lands here.

    Scalars never move: :meth:`num`, :meth:`conj`, :meth:`sqrt` and
    :meth:`is_zero` all take and return host ``complex`` values, because they
    talk to sympy on the other side.
    """

    exact = False
    array = True  # "blocks are numpy-like arrays"; tower.py branches on this

    def __init__(self, xp=None, dtype=None, tol=None):
        if xp is None:
            import numpy as xp
        self.xp = xp
        self.np = xp  # historical alias; a lot of call sites say be.np
        self.dtype = dtype if dtype is not None else xp.complex128
        self.single = xp.dtype(self.dtype).itemsize == 8
        # complex64 carries about 7 significant digits, so a 1e-9 threshold
        # would call genuine zeros nonzero.  Everything downstream compares
        # against be.tol, so deriving it here is enough.
        self.tol = tol if tol is not None else (1e-5 if self.single else 1e-9)
        self.name = getattr(xp, "__name__", "array")

    @property
    def real_dtype(self):
        return self.xp.float32 if self.single else self.xp.float64

    def to_host(self, A):
        """Bring an array back to numpy (identity when it is already there)."""
        asnumpy = getattr(self.xp, "asnumpy", None)
        return A if asnumpy is None else asnumpy(A)

    def asarray(self, A):
        return self.xp.asarray(A, dtype=self.dtype)

    @property
    def device(self):
        """Where the arrays live, for messages: ``"GPU"`` or ``"RAM"``."""
        return "GPU" if self.name == "cupy" else "RAM"

    def free_memory(self):
        """Bytes this backend can still allocate, or ``None`` if unknown.

        On the GPU that is the device's free memory plus whatever cupy's pool is
        holding unused.  On the CPU it is *physical* memory available, not
        physical plus page file: a computation that only fits by paging to disk
        is one to refuse, not to start.
        """
        if self.name == "cupy":
            try:
                free, _ = self.xp.cuda.runtime.memGetInfo()
                return int(free) + int(self.xp.get_default_memory_pool().free_bytes())
            except Exception:  # noqa: BLE001
                return None
        return host_available_memory()

    # ------------------------------------------------------------------ scalars
    def num(self, x):
        if isinstance(x, (int, float, complex)):
            return complex(x)
        if hasattr(x, "item") and getattr(x, "ndim", 1) == 0:
            return complex(x.item())  # a 0-d numpy / cupy scalar
        return complex(sp.N(sp.sympify(x), 30))

    def conj(self, x):
        return self.num(x).conjugate()

    def sqrt(self, x):
        return cmath.sqrt(self.num(x))

    def simp(self, x):
        return self.num(x)

    def to_complex(self, x):
        return self.num(x)

    def is_zero(self, x):
        return abs(self.num(x)) <= self.tol

    # ----------------------------------------------------------------- matrices
    def zeros(self, *shape):
        if len(shape) == 1 and isinstance(shape[0], tuple):
            shape = shape[0]
        return self.xp.zeros(shape, dtype=self.dtype)

    def eye(self, n):
        return self.xp.eye(n, dtype=self.dtype)

    def shape(self, A):
        return A.shape

    def dagger(self, A):
        return A.conj().T

    def mul(self, A, B):
        return A @ B

    def add(self, A, B):
        return A + B

    def sub(self, A, B):
        return A - B

    def smul(self, s, A):
        return self.num(s) * A

    def trace(self, A):
        return complex(self.xp.trace(A)) if A.size else 0j

    def mat_is_zero(self, A):
        return bool(self.xp.all(self.xp.abs(A) <= self.tol))

    def simp_mat(self, A):
        return A

    def nullspace(self, A):
        """A list of flat coordinate lists spanning ``ker(A)``."""
        xp = self.xp
        if A.shape[1] == 0:
            return []
        if A.shape[0] == 0:
            return [list(self.eye(A.shape[1])[:, j]) for j in range(A.shape[1])]
        _, s, vh = xp.linalg.svd(A)
        cut = max(A.shape) * (float(s[0]) if s.size else 0.0) * 1e-12
        rank = int((s > cut).sum())
        return [list(self.to_host(vh[j, :].conj())) for j in range(rank, A.shape[1])]

    def rank(self, A):
        """Numerical rank, cut relative to the largest singular value.

        A relative cut rather than ``matrix_rank``'s absolute one, so that the
        same threshold works for operators of any overall scale and for both
        precisions.
        """
        if A.shape[0] == 0 or A.shape[1] == 0:
            return 0
        s = self.to_host(self.xp.linalg.svd(A, compute_uv=False)).real
        if not s.size or s[0] == 0:
            return 0
        return int((s > s[0] * self.tol).sum())


class InsufficientMemory(MemoryError):
    """A computation was refused *before* allocating, because it would not fit.

    ``needed`` and ``available`` are in bytes (``available`` may be ``None``
    when it could not be determined) and ``device`` is ``"GPU"`` or ``"RAM"``.
    """

    def __init__(self, message, needed=None, available=None, device=None):
        super().__init__(message)
        self.needed = needed
        self.available = available
        self.device = device


def host_available_memory():
    """Physical memory available to this process, in bytes, or ``None``."""
    import os
    import sys

    if sys.platform == "win32":
        try:
            import ctypes

            class _Status(ctypes.Structure):
                _fields_ = [
                    ("dwLength", ctypes.c_ulong),
                    ("dwMemoryLoad", ctypes.c_ulong),
                    ("ullTotalPhys", ctypes.c_ulonglong),
                    ("ullAvailPhys", ctypes.c_ulonglong),
                    ("ullTotalPageFile", ctypes.c_ulonglong),
                    ("ullAvailPageFile", ctypes.c_ulonglong),
                    ("ullTotalVirtual", ctypes.c_ulonglong),
                    ("ullAvailVirtual", ctypes.c_ulonglong),
                    ("ullAvailExtendedVirtual", ctypes.c_ulonglong),
                ]

            status = _Status()
            status.dwLength = ctypes.sizeof(_Status)
            if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(status)):
                return int(status.ullAvailPhys)
        except Exception:  # noqa: BLE001
            return None
        return None
    try:  # Linux: MemAvailable counts reclaimable cache, which free pages do not
        with open("/proc/meminfo") as fh:
            for line in fh:
                if line.startswith("MemAvailable:"):
                    return int(line.split()[1]) * 1024
    except OSError:
        pass
    try:
        return int(os.sysconf("SC_AVPHYS_PAGES") * os.sysconf("SC_PAGE_SIZE"))
    except (AttributeError, ValueError, OSError):
        return None  # e.g. macOS, which has no portable way to ask


# the historical name: numpy at double precision
def NumpyBackend(tol=None):
    return ArrayBackend(None, None, tol)


def gpu_available():
    """Is there a GPU that cupy can actually compute on?

    Being able to ``import cupy`` is not enough: it imports without complaint on
    a machine with no NVIDIA card or no driver, and only fails at the first
    array operation.  So ask the CUDA runtime for a device instead.
    """
    try:
        import cupy as cp

        return cp.cuda.runtime.getDeviceCount() > 0
    except Exception:  # noqa: BLE001 -- not installed, no driver, no device
        return False


def get_backend(spec):
    """Accept ``'sympy'``, ``'numpy'``, ``'cupy'``, ``'cupy64'``, ``'auto'`` or an instance.

    ``'cupy'`` is ``complex128`` on the GPU and ``'cupy64'`` is ``complex64``;
    on a consumer card the second is one to two orders of magnitude faster,
    since fp64 runs at 1/64 rate there.  ``'auto'`` is ``'cupy64'`` when
    :func:`gpu_available` says so and ``'numpy'`` otherwise, so code written
    with it runs unchanged on machines with and without a GPU.
    """
    if spec is None or spec == "sympy":
        return SympyBackend()
    if spec == "auto":
        spec = "cupy64" if gpu_available() else "numpy"
    if spec == "numpy":
        return ArrayBackend()
    if spec == "numpy64":  # complex64 on the CPU, mostly for testing the tolerances
        import numpy as np

        return ArrayBackend(np, np.complex64)
    if spec in ("cupy", "cupy64"):
        if not gpu_available():
            raise RuntimeError(
                f"backend {spec!r} needs cupy and a CUDA GPU, and this machine "
                "has no usable one; use backend='numpy' (same results, on the "
                "CPU) or backend='auto' to pick whichever is available"
            )
        import cupy as cp

        return ArrayBackend(cp, cp.complex64 if spec == "cupy64" else cp.complex128)
    if isinstance(spec, str):
        raise ValueError(f"unknown backend {spec!r}")
    return spec
