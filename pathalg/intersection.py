class LevelPair:
    """Two members ``s, t`` of a family at the same level ``n``.

    ``square_s`` and ``square_t`` must be built on the same four graphs (only
    the connection may differ); the pair checks that the path spaces and the
    Markov trace agree, which is what puts both subfactors inside one ``M``.
    Use a double precision backend (``"numpy"`` or ``"cupy"``) when counting
    distinct eigenvalues -- single precision cannot tell them apart.
    """

    def __init__(self, square_s, square_t, n, backend="numpy"):
        self.s = Level(square_s, n, backend=backend)
        self.t = Level(square_t, n, backend=backend)
        self.n = n
        self.backend = be = self.s.backend
        for a, b, name in ((self.s.H, self.t.H, "H"), (self.s.K, self.t.K, "K")):
            if a.types != b.types or a.paths != b.paths:
                raise ValueError(f"the two squares have different {name} path spaces")
        for tag in ("00", "01", "10", "11"):
            ms, mt = square_s.mu[tag], square_t.mu[tag]
            if set(ms) != set(mt) or any(
                abs(complex(sp.N(ms[v] - mt[v]))) > 1e-12 for v in ms
            ):
                raise ValueError(f"the Perron-Frobenius weights differ on V{tag}")
        # V = W_s W_t^*: from the K picture of t to the K picture of s
        V = {}
        for y, Ws in self.s.W.blocks.items():
            V[y] = Ws @ self.t.W.blocks[y].conj().T
        self._V = SimpleNamespace(blocks=V)
        self._VH = SimpleNamespace(blocks={y: v.conj().T for y, v in V.items()})
        self._WtH = SimpleNamespace(
            blocks={y: w.conj().T for y, w in self.t.W.blocks.items()}
        )
        self._layouts = {}
        # Markov weights of the entries of an operator on H, per end vertex
        sq, H = square_s, self.s.H
        Z0 = sp.Add(*[sq.mu["00"][a] for a in sq.V["00"]])
        mu_end = sq.mu[H.types[H.L]]
        self.h_weight = {y: float(sp.N(mu_end[y] / (Z0 * H.P[H.L]))) for y in H.keys}
        self.xp = be.xp

    # ------------------------------------------------------------ layout
    def _layout(self, p):
        """Index data for the level-``p`` algebras ``A_{p,0}`` of both members."""
        L = self._layouts.get(p)
        if L is not None:
            return L
        s, t, be = self.s, self.t, self.backend
        plan_s = s._expectation_plan(s.K, p)
        plan_t = t._expectation_plan(t.K, p)
        if [w for w, _, _ in plan_s] != [w for w, _, _ in plan_t]:
            raise ValueError("the two K path spaces enumerate level blocks differently")
        offsets, width = {}, 0
        for w, prefixes, _ in plan_s:
            offsets[w] = (width, len(prefixes))
            width += len(prefixes) ** 2
        itemsize = be.xp.dtype(be.dtype).itemsize
        per = max(1, sum(len(b) ** 2 for b in s.K.blocks.values()))
        L = SimpleNamespace(
            p=p,
            plan_s=plan_s,
            plan_t=plan_t,
            offsets=offsets,
            width=width,
            unit_s={w: be.sqrt(v) for w, v in s._ambient_unit_weights(s.K, p).items()},
            unit_t={w: be.sqrt(v) for w, v in t._ambient_unit_weights(t.K, p).items()},
            itemsize=itemsize,
            chunk=max(1, int(_STACK_BYTES / (per * itemsize))),
        )
        self._layouts[p] = L
        return L

    def _scatter(self, space, plan, offsets, unit, Z):
        """``sum_j Z[j, c] f_j`` for every column ``c``, as K blocks ``(c, d, d)``.

        ``f_j`` is the orthonormal matrix unit basis of the level algebra:
        ``f_{sigma,tau} = sum_tails E_{sigma t, tau t} / ||.||``.
        """
        be = self.backend
        c = Z.shape[1]
        stack = {}
        for w, prefixes, per_end in plan:
            off, npre = offsets[w]
            coeff = (Z[off : off + npre * npre, :].T / unit[w]).reshape(c, npre, npre)
            for y, idx in per_end:
                Y = stack.get(y)
                if Y is None:
                    d = len(space.blocks[y])
                    Y = stack[y] = be.zeros(c, d, d)
                Y[:, idx[:, None, :], idx[None, :, :]] = coeff[:, :, :, None]
        return stack

    def _apply(self, p, Z, adjoint=False):
        """``G Z`` (or ``G^* Z``) for a ``(width, c)`` block, ``G`` the cross-Gram.

        ``G[j, k] = <f_j^(s), f_k^(t)>``: build the ``t`` element, carry it to
        the ``K`` picture of ``s`` through ``V = W_s W_t^*``, and read off its
        expectation onto ``A_{p,0}^(s)`` -- the orthogonal projection, so the
        coordinates are exactly the inner products.  The adjoint swaps roles.
        """
        L = self._layout(p)
        src, dst = (self.t, self.s) if not adjoint else (self.s, self.t)
        plan = L.plan_t if not adjoint else L.plan_s
        unit_src = L.unit_t if not adjoint else L.unit_s
        unit_dst = L.unit_s if not adjoint else L.unit_t
        stack = self._scatter(src.K, plan, L.offsets, unit_src, Z)
        stack = dst._congruence_stack(self._V if not adjoint else self._VH, stack)
        out = self.backend.zeros(L.width, Z.shape[1])
        for w, C in dst._expectation_coeffs(dst.K, stack, p):
            off, npre = L.offsets[w]
            out[off : off + npre * npre, :] = (unit_dst[w] * C.reshape(Z.shape[1], -1)).T
        return out

    # -------------------------------------------------------- the spectrum
    def cross_gram(self, p):
        """The ``dim A_{p,0} x dim A_{p,0}`` matrix ``<f_j^(s), f_k^(t)>``."""
        L = self._layout(p)
        be, xp = self.backend, self.xp
        need = L.itemsize * 3 * L.width ** 2 + 3 * _STACK_BYTES
        free = be.free_memory()
        if free is not None and need > _MEMORY_SAFETY * free:
            raise InsufficientMemory(
                f"the level {p} cross-Gram matrix ({L.width} x {L.width}) needs about "
                f"{need / 1e9:.1f} GB but only {free / 1e9:.1f} GB of {be.device} is "
                "free; use angle_top instead",
                needed=need, available=free, device=be.device,
            )
        G = be.zeros(L.width, L.width)
        for lo in range(0, L.width, L.chunk):
            hi = min(L.width, lo + L.chunk)
            E = be.zeros(L.width, hi - lo)
            E[xp.arange(lo, hi), xp.arange(hi - lo)] = 1
            G[:, lo:hi] = self._apply(p, E)
        return G

    def angle_spectrum(self, p, cluster=1e-8):
        """Exact-from-below spectrum of the angle operator at level ``p``.

        Returns a namespace with ``dim_intersection`` (the multiplicity of 1,
        i.e. ``dim C_p``), ``eigenvalues`` (those strictly inside (0, 1), in
        decreasing order, with multiplicity), ``distinct`` (those clustered at
        ``cluster``), ``top`` (the largest eigenvalue below 1, or ``None``) and
        ``dim`` (``dim A_{p,0}``).  Eigenvalues are ``cos^2`` of the angles.
        """
        import numpy as np

        be = self.backend
        tol = be.tol
        G = self.cross_gram(p)
        sv = be.to_host(self.xp.linalg.svd(G, compute_uv=False)).real
        del G
        ev = np.sort(sv ** 2)[::-1]
        cut = (1 - tol) ** 2
        ones = int((ev >= cut).sum())
        inner = ev[(ev < cut) & (ev > tol)]
        distinct = []
        for x in inner:  # decreasing
            if not distinct or distinct[-1][0] - x > cluster:
                distinct.append([x, 1])
            else:
                distinct[-1][1] += 1
        return SimpleNamespace(
            p=p,
            dim=int(ev.size),
            dim_intersection=ones,
            eigenvalues=inner,
            distinct=[(float(v), m) for v, m in distinct],
            top=float(inner[0]) if inner.size else None,
        )

    def angle_top(self, p, block=256, progress=None):
        """``dim C_p`` and the top of the spectrum, without forming ``G``.

        For levels where the cross-Gram matrix is too big.  Runs the
        eigenvalue 1 solver on ``G^* G``.  ``dim_intersection`` is exact and
        ``top``, the first eigenvalue below 1, good to about six digits (both
        checked against :meth:`angle_spectrum` at levels 4 and 5 of
        S(1,1,2,2)).  ``ritz`` lists any further Ritz values below 1 that
        happened to converge, which is often none: the eigenvalues just under
        the top cluster closely.  Counting distinct eigenvalues needs the dense
        :meth:`angle_spectrum`.
        """
        L = self._layout(p)
        be = self.backend
        X, info = unit_eigenspace(
            lambda Z: self._apply(p, self._apply(p, Z), adjoint=True),
            L.width,
            be,
            cut=(1 - be.tol) ** 2,
            block=min(L.width, block),
            chunk=L.chunk,
            progress=progress,
        )
        below = [c * c for c in info.get("ritz", []) if c * c < (1 - be.tol) ** 2]
        return SimpleNamespace(
            p=p,
            dim=L.width,
            dim_intersection=int(X.shape[1]),
            top=info["gap"][0] ** 2,
            ritz=below,
            info=info,
        )

    # ----------------------------------------------------- the intersection
    def intersection(self, p):
        """``C_p = A_{p,0}^(s) cap A_{p,0}^(t)`` with its algebra structure.

        The basis is orthonormal for the Markov inner product and is returned
        as a stack of blocks on ``H_{n+1}``; see :class:`AlgebraStructure`.
        """
        be, xp = self.backend, self.xp
        L = self._layout(p)
        G = self.cross_gram(p)
        w, U = xp.linalg.eigh(G.conj().T @ G)
        del G
        wh = be.to_host(w).real
        keep = wh >= (1 - be.tol) ** 2
        A = U[:, xp.asarray(keep.nonzero()[0])]  # coefficients in the t basis
        stack = self._scatter(self.t.K, L.plan_t, L.offsets, L.unit_t, A)
        stack = self.t._congruence_stack(self._WtH, stack)  # pull back to H
        return AlgebraStructure(self, stack)

    def algebra_A1(self, p):
        """Minimal central projections of ``A_{p,1}``, for ``C_p subset A_{p,1}``."""
        H, be = self.s.H, self.backend
        out = []
        for v, prefixes in H.level_blocks[p + 1].items():
            blocks = {}
            for y in H.keys:
                paths = H.blocks[y]
                diag = [1.0 if path[p + 1] == v else 0.0 for path in paths]
                if any(diag):
                    blocks[y] = be.xp.diag(be.xp.asarray(diag, dtype=be.dtype))
            tr = sum(self.h_weight[y] * float(be.to_host(b.trace()).real)
                     for y, b in blocks.items())
            out.append(SimpleNamespace(projection=blocks, size=len(prefixes),
                                       trace=tr, min_trace=tr / len(prefixes)))
        return out


