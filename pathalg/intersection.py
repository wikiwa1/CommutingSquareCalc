def analyse(pair, max_p=None, progress=None):
    """Everything above for ``C_1 subset ... subset C_max_p``, in one pass.

    Returns a namespace with one record per level ``p`` -- the angle spectrum
    data, ``dim C_p``, its centre and block sizes, ``||Lambda(C_p < A_{p,1})||^2``
    and the Dobrushin coefficient of the chain from ``C_1`` to ``C_p`` -- and
    the connected components of the Bratteli diagram of the ``C_p``.

    ``||Lambda(C_p < A_{p,1})||^2`` equals ``[M : P cap Q]`` at every level in
    the finite index cases it has been checked on (the subfactor itself, where
    it is ``delta^2``, and the Hadamard pairs of arXiv:2510.14499, where it is
    ``N^2 / |H|``); growth with ``p`` points to infinite index.

    A component that reaches every level carries a projection -- the sum of
    its minimal central projections -- that is central in every ``C_p``
    computed.  More than one such component is a nontrivial central
    projection of every ``C_p`` so far, which, if it persists, is central in
    ``P cap Q``.
    """
    import numpy as np

    max_p = max_p or pair.n
    records, structs = [], []
    for p in range(1, max_p + 1):
        spec = pair.angle_spectrum(p)
        C = pair.intersection(p)
        A1 = pair.algebra_A1(p)
        Lam_A = inclusion_matrix(C, [a.projection for a in A1], [a.size for a in A1],
                                 [a.min_trace for a in A1], pair)
        structs.append(C)
        records.append(SimpleNamespace(p=p, spectrum=spec, algebra=C,
                                       index_estimate=graph_norm_squared(Lam_A)))
        if progress is not None:
            progress(records[-1])

    lams, product = [], None
    records[0].dobrushin = None  # no chain before the second level
    for p in range(1, max_p):
        a, b = structs[p - 1], structs[p]
        Lam = inclusion_matrix(a, b.projections, b.sizes, b.min_traces, pair)
        lams.append(Lam)
        K = transition_matrix(Lam, a.min_traces, b.min_traces)
        product = K if product is None else product @ K
        records[p].dobrushin = dobrushin(product)

    # connected components of the Bratteli diagram (levels 1 .. max_p)
    parent = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for p, C in enumerate(structs):
        for i in range(len(C.sizes)):
            find((p, i))
    for p, Lam in enumerate(lams):
        for i, j in zip(*np.nonzero(Lam)):
            parent[find((p, int(i)))] = find((p + 1, int(j)))
    groups = {}
    for node in list(parent):
        groups.setdefault(find(node), []).append(node)
    components = []
    for nodes in groups.values():
        levels = {p for p, _ in nodes}
        first = min(levels)
        blocks = [i for p, i in nodes if p == first]
        proj = {}
        for i in blocks:
            for y, P in structs[first].projections[i].items():
                proj[y] = proj.get(y, 0) + P
        trace = sum(pair.h_weight[y] * float(pair.backend.to_host(pair.xp.trace(P)).real)
                    for y, P in proj.items())
        # a projection diagonal in the path basis is described by where its
        # paths start (a sum of minimal projections of A_{0,0})
        starts = None
        if all(float(pair.backend.to_host(pair.xp.abs(P - pair.xp.diag(pair.xp.diag(P))).max()))
               < 1e-9 for P in proj.values()):
            H = pair.s.H
            starts = sorted({H.blocks[y][k][0] for y, P in proj.items()
                             for k in range(P.shape[0])
                             if float(pair.backend.to_host(P[k, k]).real) > 0.5})
        components.append(SimpleNamespace(levels=sorted(levels), trace=trace,
                                          starts=starts, projection=proj))
    components.sort(key=lambda c: c.trace)
    return SimpleNamespace(records=records, inclusions=lams, components=components)
