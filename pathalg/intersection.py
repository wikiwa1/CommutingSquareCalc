"""Intersections of two subfactors from one family of commuting squares.

Two bi-unitary connections on the same four graphs give subfactors
``N_s, N_t`` of the *same* factor ``M``: in the ``H`` picture ``M`` is the
union of the path algebras ``A_{n,1}``, and neither those nor the Jones
projections depend on the connection.  The connection only moves the
subalgebras ``A_{n,0}^{(s)} = W_s^* (K-algebra) W_s``.  This module studies
``P cap Q = N_s cap N_t`` inside ``M``, in the spirit of Bakshi, Guin and
Guruprasad's intersections of Hadamard subfactors (arXiv:2510.14499), whose
``E_{M_N}(R_U cap R_V) = Ad_U(Delta) cap Ad_V(Delta)`` is the ``n = 1`` case of
what follows.

Everything reduces to finite dimensions, exactly:

* ``E_{N_s}(A_{n,1}) = A_{n,0}^{(s)}`` along a tower of commuting squares, so
  ``L^2(A_{n,1})`` reduces both Jones projections ``e_P, e_Q``.  The angle
  operator ``T = e_P e_Q e_P`` restricted there, ``T_n``, has
  ``spec(T_n) subset spec(T)``; the ``spec(T_n)`` increase with ``n`` and
  their union is dense in ``spec(T)``.  The non-zero part of ``spec(T_n)`` is
  the set of squared singular values of the cross-Gram matrix between
  orthonormal bases of ``A_{n,0}^{(s)}`` and ``A_{n,0}^{(t)}``
  (:meth:`LevelPair.cross_gram`).
* ``E_{P cap Q}(A_{n,1}) = C_n := A_{n,0}^{(s)} cap A_{n,0}^{(t)}``, the
  eigenvalue 1 part, and ``P cap Q`` is generated by the ``C_n``.  So the
  Bratteli diagram of ``C_1 subset C_2 subset ...`` with the Markov trace
  decides whether ``P cap Q`` is a factor: its centre is the space of bounded
  harmonic functions of the Markov chain the trace defines on that diagram
  (:func:`transition_matrix`, :func:`dobrushin`).
* If ``[M : P cap Q] < infinity`` then ``e_P, e_Q`` lie in the
  finite-dimensional ``(P cap Q)' cap M_1`` and ``spec(T)`` is finite.  A
  number of distinct eigenvalues that keeps growing with ``n`` rules finite
  index out.
"""

from __future__ import annotations

from types import SimpleNamespace

import sympy as sp

