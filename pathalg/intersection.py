class AlgebraStructure:
    """A finite-dimensional *-algebra on ``H_{n+1}`` given by a basis stack.

    Computes the centre, the minimal central projections, the block sizes and
    the trace of a minimal projection in each block -- the data of a Bratteli
    diagram vertex set.
    """

    def __init__(self, pair, stack, seed=0):
        import numpy as np

        self.pair = pair
        self.stack = stack
        be, xp = pair.backend, pair.xp
        self.dim = int(next(iter(stack.values())).shape[0]) if stack else 0
        rng = np.random.default_rng(seed)
        r = self.dim

        def combo(coeffs):
            c = xp.asarray(coeffs, dtype=be.dtype)
            return {y: xp.tensordot(c, B, axes=1) for y, B in stack.items()}

        # centre: the commutant, inside span(C), of three random elements
        rows = []
        for _ in range(3):
            x = combo(rng.standard_normal(r) + 1j * rng.standard_normal(r))
            parts = []
            for y, B in stack.items():
                comm = B @ x[y] - x[y] @ B  # [b_i, x] for every i
                parts.append((comm * pair.h_weight[y] ** 0.5).reshape(r, -1))
            rows.append(xp.concatenate(parts, axis=1))
        Mrows = xp.concatenate(rows, axis=1)
        gram = Mrows.conj() @ Mrows.T  # r x r, PSD
        ev, vec = xp.linalg.eigh((gram + gram.conj().T) / 2)
        evh = be.to_host(ev).real
        scale = max(float(evh[-1]), 1.0) if evh.size else 1.0
        centre = vec[:, xp.asarray((evh <= 1e-9 * scale).nonzero()[0])]
        self.centre_dim = int(centre.shape[1])

        # minimal central projections: spectral projections of a random
        # self-adjoint central element, clustered across all blocks
        c = rng.standard_normal(self.centre_dim) + 1j * rng.standard_normal(self.centre_dim)
        z = combo(centre @ xp.asarray(c, dtype=be.dtype))
        vals, vecs = {}, {}
        for y, Z in z.items():
            h = (Z + Z.conj().T) / 2
            e, v = xp.linalg.eigh(h)
            vals[y], vecs[y] = be.to_host(e).real, v
        allvals = np.sort(np.concatenate(list(vals.values())))
        spread = max(1.0, float(np.abs(allvals).max())) if allvals.size else 1.0
        levels = []
        for x in allvals:
            if not levels or x - levels[-1][-1] > 1e-7 * spread:
                levels.append([x])
            else:
                levels[-1].append(x)
        centres = [float(np.mean(g)) for g in levels]
        self.projections = []
        for lam in centres:
            proj = {}
            for y in z:
                sel = np.abs(vals[y] - lam) <= 1e-6 * spread
                if sel.any():
                    v = vecs[y][:, xp.asarray(sel.nonzero()[0])]
                    proj[y] = v @ v.conj().T
            self.projections.append(proj)
        if len(self.projections) != self.centre_dim:
            raise ArithmeticError(
                f"centre has dimension {self.centre_dim} but a generic central "
                f"element has {len(self.projections)} distinct eigenvalues"
            )

        # block sizes b_i (dim q_i C = b_i^2) and minimal-projection traces
        self.sizes, self.min_traces = [], []
        for proj in self.projections:
            parts = []
            for y, B in stack.items():
                if y in proj:
                    parts.append((proj[y] @ B * pair.h_weight[y] ** 0.5).reshape(r, -1))
            Q = xp.concatenate(parts, axis=1)
            sv = be.to_host(xp.linalg.svd(Q, compute_uv=False)).real
            rank = int((sv > 1e-7 * max(float(sv[0]), 1e-300)).sum()) if sv.size else 0
            b = round(rank ** 0.5)
            if b * b != rank:
                raise ArithmeticError(f"a central summand has dimension {rank}, not a square")
            tr = sum(pair.h_weight[y] * float(be.to_host(P.trace()).real)
                     for y, P in proj.items())
            self.sizes.append(b)
            self.min_traces.append(tr / b)

    def __repr__(self):
        return (f"<AlgebraStructure dim={self.dim} centre={self.centre_dim} "
                f"blocks={self.sizes}>")


def _trace_of_product(pair, P, Q):
    xp = pair.xp
    total = 0.0
    for y in P:
        if y in Q:
            total += pair.h_weight[y] * float(pair.backend.to_host(xp.trace(P[y] @ Q[y])).real)
    return total


def inclusion_matrix(small, big_projections, big_sizes, big_min_traces, pair):
    """``Lambda[i, j]`` = multiplicity of block ``i`` of ``small`` in block ``j``.

    ``tau(q_i p_j) = Lambda_ij b_i t_j``.  The entries are rounded and checked
    to be integers, and the block sizes checked to add up.
    """
    import numpy as np

    Lam = np.zeros((len(small.projections), len(big_projections)))
    for i, q in enumerate(small.projections):
        for j, P in enumerate(big_projections):
            Lam[i, j] = _trace_of_product(pair, q, P) / (small.sizes[i] * big_min_traces[j])
    R = np.rint(Lam)
    if np.abs(Lam - R).max() > 1e-6:
        raise ArithmeticError(f"inclusion matrix is not integral:\n{Lam}")
    R = R.astype(int)
    if not np.array_equal(R.T @ np.asarray(small.sizes), np.asarray(big_sizes)):
        raise ArithmeticError("block sizes do not add up along the inclusion")
    return R


def transition_matrix(Lam, small_min_traces, big_min_traces):
    """``K[i, j] = Lambda_ij t_j / t'_i``: ``E_small`` on the centres, as a chain.

    Row stochastic.  Bounded harmonic functions of the chain it defines along
    the tower are the centre of the inductive limit.
    """
    import numpy as np

    K = Lam * np.asarray(big_min_traces)[None, :] / np.asarray(small_min_traces)[:, None]
    return K


def dobrushin(K):
    """Dobrushin ergodicity coefficient: ``max_{i,i'} ||K_i - K_i'||_1 / 2``."""
    import numpy as np

    K = np.asarray(K)
    if K.shape[0] < 2:
        return 0.0
    diff = np.abs(K[:, None, :] - K[None, :, :]).sum(axis=2) / 2
    return float(diff.max())


def graph_norm_squared(Lam):
    """``||Lambda||^2``, the largest eigenvalue of ``Lambda Lambda^T``."""
    import numpy as np

    Lam = np.asarray(Lam, dtype=float)
    return float(np.linalg.eigvalsh(Lam @ Lam.T).max()) if Lam.size else 0.0


